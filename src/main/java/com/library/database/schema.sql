-- ============================================================
-- LIBRARY MANAGEMENT SYSTEM
-- DATABASE SCHEMA
-- Supabase / PostgreSQL
-- ============================================================


-- ============================================================
-- 1. USERS TABLE
-- ============================================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL,

    register_number VARCHAR(50) UNIQUE,

    email VARCHAR(150) UNIQUE NOT NULL,

    password VARCHAR(255) NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'STUDENT',

    department VARCHAR(100),

    phone VARCHAR(20),

    created_at TIMESTAMPTZ DEFAULT NOW(),

    CONSTRAINT users_role_check
    CHECK (role IN ('ADMIN', 'STUDENT'))
);


-- ============================================================
-- 2. BOOKS TABLE
-- ============================================================

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    book_id VARCHAR(50) UNIQUE NOT NULL,

    title VARCHAR(200) NOT NULL,

    author VARCHAR(150) NOT NULL,

    isbn VARCHAR(50),

    category VARCHAR(100),

    quantity INTEGER NOT NULL DEFAULT 1,

    available_quantity INTEGER NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ DEFAULT NOW(),

    CONSTRAINT books_quantity_check
    CHECK (quantity >= 0),

    CONSTRAINT books_available_quantity_check
    CHECK (available_quantity >= 0),

    CONSTRAINT books_available_not_greater
    CHECK (available_quantity <= quantity)
);


-- ============================================================
-- 3. BORROWINGS TABLE
-- ============================================================

CREATE TABLE borrowings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    book_id BIGINT NOT NULL,

    student_id BIGINT NOT NULL,

    issue_date TIMESTAMPTZ DEFAULT NOW(),

    due_date TIMESTAMPTZ NOT NULL,

    return_date TIMESTAMPTZ,

    status VARCHAR(20) NOT NULL DEFAULT 'BORROWED',

    fine DECIMAL(10,2) DEFAULT 0,

    CONSTRAINT borrowing_status_check
    CHECK (
        status IN ('BORROWED', 'RETURNED', 'OVERDUE')
    ),

    CONSTRAINT borrowings_book_fk
    FOREIGN KEY (book_id)
    REFERENCES books(id)
    ON DELETE CASCADE,

    CONSTRAINT borrowings_student_fk
    FOREIGN KEY (student_id)
    REFERENCES users(id)
    ON DELETE CASCADE
);


